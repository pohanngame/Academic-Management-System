CREATE TABLE `publication_venue_dataset` (
    `id` BIGINT NOT NULL AUTO_INCREMENT,
    `dataset_key` VARCHAR(64) NOT NULL,
    `data_name` VARCHAR(255) NOT NULL,
    `data_year` INT NOT NULL,
    `source_kind` VARCHAR(64) NOT NULL,
    `source_page` VARCHAR(1024) NOT NULL,
    `source_sha256` CHAR(64) NOT NULL,
    `record_count` INT NOT NULL,
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_publication_venue_dataset_key` (`dataset_key`),
    CONSTRAINT `chk_publication_venue_dataset_year` CHECK (`data_year` BETWEEN 1900 AND 2200)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `publication_venue_reference` (
    `id` BIGINT NOT NULL AUTO_INCREMENT,
    `dataset_id` BIGINT NOT NULL,
    `venue_type` VARCHAR(16) NOT NULL,
    `category_id` INT NOT NULL,
    `category_name` VARCHAR(255) NOT NULL,
    `category_name_en` VARCHAR(255) NULL,
    `ccf_rank` CHAR(1) NOT NULL,
    `abbreviation` VARCHAR(128) NULL,
    `standard_name` VARCHAR(500) NOT NULL,
    `normalized_name` VARCHAR(500) NOT NULL,
    `normalized_abbreviation` VARCHAR(128) NULL,
    `aliases` VARCHAR(2000) NULL,
    `publisher` VARCHAR(500) NULL,
    `source_url` VARCHAR(1024) NULL,
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_publication_venue_reference` (`dataset_id`, `venue_type`, `category_id`, `ccf_rank`, `normalized_name`),
    KEY `idx_publication_venue_normalized_name` (`venue_type`, `normalized_name`),
    KEY `idx_publication_venue_abbreviation` (`venue_type`, `normalized_abbreviation`),
    CONSTRAINT `fk_publication_venue_dataset` FOREIGN KEY (`dataset_id`) REFERENCES `publication_venue_dataset` (`id`) ON DELETE CASCADE,
    CONSTRAINT `chk_publication_venue_type` CHECK (`venue_type` IN ('JOURNAL', 'CONFERENCE')),
    CONSTRAINT `chk_publication_venue_rank` CHECK (`ccf_rank` IN ('A', 'B', 'C'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE `journal_metric_reference` (
    `id` BIGINT NOT NULL AUTO_INCREMENT,
    `journal_name` VARCHAR(500) NOT NULL,
    `normalized_name` VARCHAR(500) NOT NULL,
    `issn` VARCHAR(16) NULL,
    `eissn` VARCHAR(16) NULL,
    `data_year` INT NOT NULL,
    `impact_factor` DECIMAL(10,6) NOT NULL,
    `jcr_quartile` CHAR(2) NOT NULL,
    `subject_name` VARCHAR(255) NULL,
    `source_name` VARCHAR(500) NOT NULL,
    `source_url` VARCHAR(1024) NOT NULL,
    `source_license` VARCHAR(255) NOT NULL,
    `source_sha256` CHAR(64) NOT NULL,
    `active` TINYINT(1) NOT NULL DEFAULT 1,
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_journal_metric_reference` (`normalized_name`, `data_year`, `source_sha256`),
    KEY `idx_journal_metric_issn_year` (`issn`, `data_year`),
    KEY `idx_journal_metric_eissn_year` (`eissn`, `data_year`),
    KEY `idx_journal_metric_name_year` (`normalized_name`, `data_year`),
    CONSTRAINT `chk_journal_metric_year` CHECK (`data_year` BETWEEN 1900 AND 2200),
    CONSTRAINT `chk_journal_metric_impact` CHECK (`impact_factor` >= 0),
    CONSTRAINT `chk_journal_metric_quartile` CHECK (`jcr_quartile` IN ('Q1', 'Q2', 'Q3', 'Q4'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

